const CHECKOUT_ROUTE = [
  " import { checkout } from \"../../checkout/checkout\"",
  " import { OutOfStockError } from \"../../inventory/stock-level\"",
  " import { readCart } from \"../../cart/cart\"",
  " ",
  "#region postCheckout",
  " export const postCheckout = async (request: Request, reply: Reply) => {",
  "   const cart = await readCart(request.params.cartId)",
  "   try {",
  "     return await checkout(cart)",
  "   } catch (error) {",
  "     if (error instanceof OutOfStockError) return reply.code(409).send({ sku: error.sku })",
  "     throw error",
  "   }",
  " }",
  "#endregion postCheckout",
].join("\n")

