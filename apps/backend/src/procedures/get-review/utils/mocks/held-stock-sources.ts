const STOCK_LEVEL = [
  " import { activeHolds } from \"./holds\"",
  " import { readStock } from \"./stock-repository\"",
  "+import type { CartLine } from \"../cart/cart-line\"",
  " ",
  " export class OutOfStockError extends Error {",
  "   public constructor(public readonly sku: string) {",
  "     super(\"Not enough stock for \" + sku)",
  "   }",
  " }",
  " ",
  "#region availableUnits",
  "-export const availableUnits = async (sku: string): Promise<number> => {",
  "-  const stock = await readStock(sku)",
  "-  return stock.onHand",
  "-}",
  "+export const availableUnits = async (sku: string, held = 0): Promise<number> => {",
  "+  const [stock, holds] = await Promise.all([readStock(sku), activeHolds(sku)])",
  "+  const heldByOthers = holds.reduce((total, hold) => total + hold.units, 0) - held",
  "+  return stock.onHand - heldByOthers",
  "+}",
  "#endregion availableUnits",
  " ",
  "#region assertInStock",
  "-export const assertInStock = async (sku: string, units: number): Promise<void> => {",
  "-  if ((await availableUnits(sku)) < units) throw new OutOfStockError(sku)",
  "+export const assertInStock = async (line: CartLine): Promise<void> => {",
  "+  const available = await availableUnits(line.sku, line.held)",
  "+  if (available < line.units) throw new OutOfStockError(line.sku)",
  " }",
  "#endregion assertInStock",
].join("\n")

