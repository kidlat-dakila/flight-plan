          "+        query = query.where(Pokemon.trainer_id == trainer_id)",
          "+    return list(session.scalars(query))",
          "+",
          "+",
          "+def find_pokemon(session: Session, pokemon_id: int) -> Pokemon:",
          "+    pokemon = session.get(Pokemon, pokemon_id)",
          "+    if pokemon is None:",
          "+        raise NotFoundError(\"pokemon\", pokemon_id)",
          "+    return pokemon",
          "+",
          "+",
          "+def create_pokemon(session: Session, draft: PokemonCreate) -> Pokemon:",
