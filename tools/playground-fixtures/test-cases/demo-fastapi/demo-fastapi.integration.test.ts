          "+        find_trainer(session, draft.trainer_id)",
          "+    pokemon = Pokemon(**draft.model_dump())",
          "+    session.add(pokemon)",
          "+    session.commit()",
          "+    session.refresh(pokemon)",
          "+    return pokemon",
